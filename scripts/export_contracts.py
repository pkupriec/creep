"""Reproduce schema/types from Python DTOs, or fail if versioned outputs drift."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.contracts.api import PUBLIC_MODELS  # noqa: E402
from app.contracts.errors import ErrorResponse  # noqa: E402
from app.contracts.graph import Graph  # noqa: E402


def schema_bundle() -> dict:
    definitions: dict = {}
    for model in (Graph, *PUBLIC_MODELS, ErrorResponse):
        schema = model.model_json_schema(by_alias=True)
        children = schema.pop("$defs", {})
        for name, definition in {**children, model.__name__: schema}.items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"Conflicting JSON Schema definition: {name}")
            definitions[name] = definition
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$ref": "#/$defs/Graph",
        "$defs": dict(sorted(definitions.items())),
    }


def typescript_type(schema: dict | bool) -> str:
    if schema is True:
        return "JsonValue"
    if schema is False:
        return "never"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    for keyword in ("anyOf", "oneOf"):
        if keyword in schema:
            return " | ".join(typescript_type(value) for value in schema[keyword])
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind in {"number", "integer"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(typescript_type(item) for item in schema["prefixItems"]) + "]"
        return "Array<" + typescript_type(schema.get("items", True)) + ">"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if not properties:
            additional = schema.get("additionalProperties", True)
            return "Record<string, " + typescript_type(additional) + ">"
        required = set(schema.get("required", []))
        fields = [
            json.dumps(name)
            + ("" if name in required else "?")
            + ": "
            + typescript_type(value)
            + ";"
            for name, value in properties.items()
        ]
        return "{ " + " ".join(fields) + " }"
    if not schema or set(schema) <= {"title", "description", "default"}:
        return "JsonValue"
    raise ValueError(f"Unsupported JSON Schema construct: {schema}")


def render_typescript(bundle: dict) -> str:
    lines = [
        "// Generated by scripts/export_contracts.py. Do not edit.",
        "// JSON Schema is authoritative for numeric, pattern and topology validation.",
        "",
    ]
    for name, schema in bundle["$defs"].items():
        if name == "JsonValue" and schema == {}:
            # Pydantic's empty JSON-value schema means every JSON value, not arbitrary JS.
            value_type = (
                "string | number | boolean | null | Array<JsonValue> | { [key: string]: JsonValue }"
            )
        else:
            value_type = typescript_type(schema)
        lines.append(f"export type {name} = {value_type};")
    lines.extend(
        [
            "",
            "export type Node = Graph['nodes'][number];",
            "export type Edge = Graph['edges'][number];",
            "",
        ]
    )
    return "\n".join(lines)


def generated_outputs() -> dict[str, str]:
    bundle = schema_bundle()
    return {
        "frontend/src/contracts/schema.json": json.dumps(bundle, ensure_ascii=False, indent=2)
        + "\n",
        "frontend/src/contracts/generated.ts": render_typescript(bundle),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output-root", type=Path, default=ROOT)
    args = parser.parse_args()
    failed = False
    for relative, expected in generated_outputs().items():
        path = args.output_root / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                print(f"Contract drift: {relative}", file=sys.stderr)
                failed = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if not failed:
        print(
            "Generated contracts match Python DTOs"
            if args.check
            else "Generated schema and TypeScript"
        )
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
